package main

import (
	"encoding/hex"
	"testing"
)

// 向量由 edge-tts（2026-10）的 drm.generate_sec_ms_gec_v2 / _token_hash 生成
func TestEdgeGECv2(t *testing.T) {
	cases := []struct {
		unix int64
		want string
	}{
		{0, "52BC7A17B50DFEC9-28C4394775C8751CD2F6859C030C06DB1489ACAB3B3A7651831FC26895177ED6"},
		{299, "52BC7A17B50DFEC9-28C4394775C8751CD2F6859C030C06DB1489ACAB3B3A7651831FC26895177ED6"},
		{300, "F7535A20A262E331-28675BF85C7106BBF20035A78FCB0B6890813EAD5C3B983EF3424931B720BABB"},
		{1700000000, "2CD23A2CA0B2595A-F3C846C370E05F9CC83ACC5F995C5F5D87A4D0F14CE8936A0F902E64099E38A2"},
		{1700000123, "0919602B5750900A-EC9DD394F23CB5635CF62A0E8E24136DCD32B26D10C543B10082E482D7516397"},
		{1760000000, "6D50DDDB91812C33-DD68EFB01898B0750C9797D51A5FF93471DFDAE6888A1039D532CBDCCE54545D"},
		{1792222488, "E829C480CBD394D9-A90FF04CF9BEBE8C596A3E0816F66F2A6E87FD75AC37D67DD14EDF2CCC174DA2"},
		{1800000000, "99E54519B490BE5C-E162DB0977FBDCB9B86DD8148BF1BCDC3C0303176CE39852A42B415935C20654"},
		{2000000000, "2D62557F1142BC5D-FD9C30C68FF194A5EE6B45FEFC5E2BA1D1239F88A90569AB55CFFFAA7799F40E"},
		{2147483647, "96AE288915A09C99-EB52B45DB68387A1383783E40D42BBBD69D4DCCDF2540629BD4E7FB2E3287822"},
		{4102444800, "DD230DB44FEE2FD7-DA0D4FA797866E36C992FABB81DD2F9DB37EB74D675D63228277003DCD3F9F8C"},
	}
	for _, c := range cases {
		if got := edgeGECv2(c.unix); got != c.want {
			t.Errorf("edgeGECv2(%d) = %s, want %s", c.unix, got, c.want)
		}
	}
	hashes := []struct{ data, cs, sha string }{
		{"31323334353637", "CF8264F204E37578", "4B4B1B27BCB09F84AE904B387373DA006A64E1B4EFCC1BAF1D6F289D44E6DAC8"},
		{"3132333435363738", "FF68734F9C22A4D6", "F7CC197E8281C6E3B1AE9BC5214DFF71C9E86469BCFAA2DABD23507CDA13FC63"},
		{"6162636465666768696a6b6c6d6e6f707172737475767778797a303132333435363738394142434445464748494a4b4c4d4e4f505152535455565758595a", "19E9B66C8516B927", "487D4CE710368B62C684EFBCD6BD1EC7D23AAC09AA4F5442B0962DA54ED0C012"},
	}
	for _, c := range hashes {
		d, _ := hex.DecodeString(c.data)
		cs, sha, err := gecTokenHash(d)
		if err != nil || cs != c.cs || sha != c.sha {
			t.Errorf("gecTokenHash(%s) = %s %s %v", c.data, cs, sha, err)
		}
	}
	long := make([]byte, 200)
	for i := range long {
		long[i] = 'x'
	}
	if cs, sha, _ := gecTokenHash(long); cs != "53228090875E78AD" || sha != "FF76E97564A5EE9A6A8EEB2E8575998C96122A74A7C7CF7F79529C6DE05125AE" {
		t.Errorf("200 字节：%s %s", cs, sha)
	}
}
